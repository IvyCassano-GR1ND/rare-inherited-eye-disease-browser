import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import core from '../src/clinical-core.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=f=>fs.readFile(path.join(root,f),'utf8');
const data=JSON.parse(await read('data/catalog.json'));
const records=core.readCSV(await read('data/clinical.csv'),data.entries,{allowEmpty:true});
const clinical={version:1,revision:createHash('sha256').update(JSON.stringify(records)).digest('hex').slice(0,16),records};
const json=x=>JSON.stringify(x).replace(/</g,'\\u003c');
const pieces={CSS:await read('src/styles.css'),CATALOG:json(data),CLINICAL:json(clinical),CORE:await read('src/clinical-core.js'),APP:await read('src/app.js')+'\n'+await read('src/clinical-ui.js')};
const result=(await read('src/index.html')).replace(/__(CSS|CATALOG|CLINICAL|CORE|APP)__/g,(_,key)=>pieces[key]);
await fs.writeFile(path.join(root,'index.html'),result);
await fs.mkdir(path.join(root,'dist'),{recursive:true});
await fs.writeFile(path.join(root,'dist/index.html'),result);
for(const file of ['_headers','_redirects'])await fs.copyFile(path.join(root,file),path.join(root,'dist',file));
await fs.writeFile(path.join(root,'templates/clinical-template.csv'),core.toCSV([]));
await fs.writeFile(path.join(root,'templates/disease-list.csv'),'\uFEFFORPHA编号,中文名称,英文名称,条目类型\r\n'+data.entries.filter(e=>!['Category','Clinical group'].includes(e.type)).map(e=>[e.code,e.nameZh,e.name,e.type].map(v=>'"'+String(v).replace(/"/g,'""')+'"').join(',')).join('\r\n'));
console.log(`Built index.html: ${data.entries.length} entries, ${data.meta.definitionCount} definitions, ${records.length} clinical records.`);
